_SUPERSCRIPT_MAP = str.maketrans("0123456789", "⁰¹²³⁴⁵⁶⁷⁸⁹")


def _format_valence_config(config: str) -> str:
    parts = []
    token_pattern = re.compile(r"(\\[[^\\]]+\\]|\\d+[spdf]\\d+)")
    for match in token_pattern.finditer(config):
        token = match.group(0)
        if token.startswith("[") and token.endswith("]"):
            parts.append(token)
            continue
        head = []
        tail = []
        for idx, char in enumerate(token):
            if char.isalpha():
                head.append(token[: idx + 1])
                tail.append(token[idx + 1 :])
                break
        if head and tail:
            parts.append(f"{head[0]}{tail[0].translate(_SUPERSCRIPT_MAP)}")
        else:
            parts.append(token)
    return "".join(parts) if parts else config


def atomic_weight(symbol: str) -> str:
    return ATOMIC_WEIGHTS.get(symbol, "")


def valence_electron_config(symbol: str) -> str:
    config = VALENCE_ELECTRON_CONFIGS.get(symbol, "")
    if not config:
        return ""
    return _format_valence_config(config)

